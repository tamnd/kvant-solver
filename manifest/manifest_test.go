func TestErrataKeepAHumanResolution(t *testing.T) {
	e := &Errata{}
	e.Add(Erratum{
		Issue:   "kvant_1975_1",
		Kind:    "page",
		Subject: "Равенства из спичек",
		Claims:  map[string]string{"kvant.digital": "12", "kvant.mccme.ru": "13"},
	})
	if len(e.Open()) != 1 {
		t.Fatal("a fresh disagreement should be open")
	}
	e.Entries[0].Resolution = "the title appears on page 12 in the scan"
	e.Entries[0].Taken = "kvant.digital"

	// Running the sync again finds the same disagreement. Losing the answer a
	// person wrote is the one thing this file must never do.
	e.Add(Erratum{
		Issue:   "kvant_1975_1",
		Kind:    "page",
		Subject: "Равенства из спичек",
		Claims:  map[string]string{"kvant.digital": "12", "kvant.mccme.ru": "13"},
	})
	e.Sort()
	if e.Count != 1 {
		t.Errorf("%d entries after a resync", e.Count)
	}
	if len(e.Open()) != 0 {
		t.Error("the resync reopened a resolved disagreement")
	}
	if e.Entries[0].Taken != "kvant.digital" {
		t.Error("the resolution was lost")
	}
}

func TestCarryDropsWhatIsNoLongerTrue(t *testing.T) {
	old := &Errata{Entries: []Erratum{
		{Issue: "kvant_1975_1", Kind: "toc_row", Subject: "Равенства из спичек"},
		{Issue: "kvant_1975_2", Kind: "toc_row", Subject: "В номере", Resolution: "the mirror lost the row"},
		{Issue: "kvant_1993_2", Kind: "number", Subject: "2"},
	}}
	// This run looked at 1975 again and found one of the two disagreements.
	fresh := &Errata{}
	fresh.Add(Erratum{Issue: "kvant_1975_2", Kind: "toc_row", Subject: "В номере"})
	fresh.Add(Erratum{Issue: "kvant_1993_2", Kind: "number", Subject: "2"})
	fresh.Carry(old, func(x Erratum) bool { return KeyYear(x.Issue) == 1975 })
	fresh.Sort()

	if fresh.Count != 2 {
		t.Fatalf("%d entries, want 2", fresh.Count)
	}
	// A parser fix means the disagreement is gone, and the entry has to go with
	// it. An errata file that only ever grows stops being a list of findings.
	for _, x := range fresh.Entries {
		if x.Subject == "Равенства из спичек" {
			t.Error("a disagreement that is no longer there survived the resync")
		}
	}
	if fresh.Entries[0].Resolution == "" {
		t.Error("the resolution was lost, which is the one thing Carry must not do")
	}
}

func TestCarryLeavesTheYearsARunDidNotVisitAlone(t *testing.T) {
	old := &Errata{Entries: []Erratum{
		{Issue: "kvant_1980_4", Kind: "toc_row", Subject: "Гипербола"},
	}}
	fresh := &Errata{}
	fresh.Carry(old, func(x Erratum) bool { return KeyYear(x.Issue) == 1975 })
	// A sync over 1975 says nothing about 1980, and dropping the entry would
	// read as a claim that 1980 is clean.
	if len(fresh.Entries) != 1 {
		t.Errorf("%d entries, the 1980 finding should have been carried across", len(fresh.Entries))
	}
}
