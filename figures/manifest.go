package figures

import (
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

// Base is where the crops are served from. They are not in the site, which is
// text and has a file limit, and not in the corpus, which is text and in git.
const Base = "https://kvant-figures.tamnd.com"

// A Manifest is the figures cut out of one issue.
type Manifest struct {
	Issue   string  `yaml:"issue"`
	Figures []Entry `yaml:"figures"`
}

// An Entry is one crop: which sheet it came from, the anchor it belongs to,
// and where it is served.
type Entry struct {
	Page   int    `yaml:"page"`             // the page file's index
	N      int    `yaml:"n"`                // its place among the page's figures, from one
	Number string `yaml:"number,omitempty"` // the printed figure number
	Key    string `yaml:"key,omitempty"`    // the anchor's key, see Anchor
	Group  bool   `yaml:"group,omitempty"`  // one of the page's figures, all put at its first anchor
	File   string `yaml:"file"`             // under Base
	Width  int    `yaml:"width"`
	Height int    `yaml:"height"`
}

// URL is where the crop is served.
func (e Entry) URL() string { return Base + "/" + e.File }

// Path is where an issue's manifest lives in the corpus.
func Path(root, issue string) string {
	return filepath.Join(root, "figures", issue+".yaml")
}

// Read loads an issue's manifest. An issue nobody has cut figures from has
// none, which is not an error.
func Read(root, issue string) (*Manifest, error) {
	data, err := os.ReadFile(Path(root, issue))
	if os.IsNotExist(err) {
		return &Manifest{Issue: issue}, nil
	}
	if err != nil {
		return nil, err
	}
	m := &Manifest{}
	if err := yaml.Unmarshal(data, m); err != nil {
		return nil, fmt.Errorf("%s: %w", Path(root, issue), err)
	}
	return m, nil
}

// Write saves an issue's manifest, or removes it when it is empty.
func (m *Manifest) Write(root string) error {
	path := Path(root, m.Issue)
	if len(m.Figures) == 0 {
		err := os.Remove(path)
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	data, err := yaml.Marshal(m)
	if err != nil {
		return err
	}
	head := "# Generated by kvant figures. The crops are served under " + Base + ".\n"
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, append([]byte(head), data...), 0o644)
}
